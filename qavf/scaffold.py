"""Configuration scaffolding: profiling data into QA limits, ``qavf init`` and JSON Schema.

``qavf init`` writes a minimal starter (the project, its datasets and their
inferred schemas, and pointers to the next steps); ``qavf init --full`` writes the
complete reference listing every discovered rule and every setting's default.
Given data files, each dataset gets a schema whose QA limits (types, nullability,
observed bounds, allowed values) are inferred from the data. Inferred limits are a
starting point to review, not a verdict: they encode whatever the sample contained,
including its errors.
"""

from __future__ import annotations

import functools
import json
from collections.abc import Mapping
from datetime import UTC, datetime
from typing import Any

import yaml
from pydantic import Field, create_model

from qavf._version import __version__
from qavf.checks.catalog import PluginDefinition, definition_for
from qavf.checks.items import RunSettings, checks_union
from qavf.checks.schema import check_item_models
from qavf.engine.registry import RuleRegistry
from qavf.profiling import profile_frame as profile_frame
from qavf.profiling.values import validate_margin as validate_margin
from qavf.settings import (
    DatasetSpec,
    EngineSettings,
    PluginSettings,
    QAVFSettings,
    ReportSettings,
    SchemaSpec,
)
from qavf.sources.base import SourceRegistry

SCHEMA_FILENAME = "qavf.schema.json"


# ------------------------------------------------------------------ rendering
def _dump(value: Any, indent: int = 0) -> str:
    text = yaml.safe_dump(value, sort_keys=False, default_flow_style=False, allow_unicode=True)
    pad = " " * indent
    return "".join(pad + line if line.strip() else line for line in text.splitlines(True))


DOCS_URL = "https://github.com/AhmedAredah/qavf/blob/main/docs/"


class StarterEntries:
    """Dataset entries for the minimal starter: no null or default-valued settings."""

    @classmethod
    def entry(cls, raw: Mapping[str, Any]) -> dict[str, Any]:
        """``raw`` without empty settings, and its schema without default values."""
        entry = cls.pruned(raw)
        schema = entry.get("schema")
        if isinstance(schema, dict):
            defaults = _schema_defaults()
            for key in [key for key in schema if key in defaults]:
                if schema[key] == defaults[key]:
                    del schema[key]
        return entry

    @classmethod
    def pruned(cls, raw: Mapping[str, Any]) -> dict[str, Any]:
        """A copy of ``raw`` with null values and empty lists and mappings left out."""
        result: dict[str, Any] = {}
        for key, value in raw.items():
            kept = cls.pruned(value) if isinstance(value, Mapping) else value
            if kept is None or (isinstance(kept, list | dict) and not kept):
                continue
            result[key] = kept
        return result


@functools.cache
def _schema_defaults() -> dict[str, Any]:
    """The scalar defaults of a dataset schema's own settings (``min_rows``, ...)."""
    return {
        name: field.default
        for name, field in SchemaSpec.model_fields.items()
        if isinstance(field.default, int | float | str | bool)
    }


def render_config(
    registry: RuleRegistry,
    datasets: Mapping[str, Mapping[str, Any]] | None = None,
    *,
    project: str = "QA run",
    schema_reference: str | None = SCHEMA_FILENAME,
    full: bool = True,
) -> str:
    """Render a commented YAML configuration.

    Args:
        registry: Installed rules; the full reference lists their checks in a comment.
        datasets: Dataset entries (``path``/``source`` plus ``schema``) to include.
        project: Project name.
        schema_reference: JSON Schema path for the editor header comment, or ``None``.
        full: The complete reference with every setting's default (``qavf init
            --full``); ``False`` renders the minimal starter ``qavf init`` writes,
            which never pins defaults such as ``engine.execution_mode``.
    """
    if not full:
        return _render_starter(datasets, project=project, schema_reference=schema_reference)
    stamp = datetime.now(UTC).strftime("%Y-%m-%d")
    lines = []
    if schema_reference:
        lines.append(f"# yaml-language-server: $schema={schema_reference}")
    lines += [
        f"# QAVF {__version__} configuration, generated by `qavf init` on {stamp}.",
        "# Schema contracts (columns, keys, foreign keys) always run; other checks run only",
        "# where a `checks` list configures them. `qavf list-checks` lists every check.",
        "# Inferred column limits reflect the profiled data; review them before relying on them.",
        "",
        _dump({"project": project}).rstrip(),
        "",
        "# Reuse: named values (${vars.years}), shared files and default check settings.",
        "#vars: {years: 2020..2023}",
        "#include: [shared/contracts.yaml]",
        "#defaults: {change_rate: {max: 0.25}}",
        "",
        "# Datasets: where data comes from, the QA limits for each column, and its checks.",
        "# Sources: path (file/glob), or source: {type: file|query|database|python, ...}.",
    ]
    if datasets:
        lines.append("datasets:")
        for name, entry in datasets.items():
            lines.append(_dump({name: dict(entry)}, 2).rstrip())
    else:
        lines += [
            "datasets: {}",
            "#  traffic:",
            "#    path: data/{district}/traffic.csv",
            "#    across: {district: [north, south]}   # copies traffic@north and traffic@south",
            "#    schema:",
            "#      primary_key: [site_id, year]",
            "#      columns:",
            "#        year: {dtype: int, between: [2000, 2030]}",
            "#        aadt:",
            "#          dtype: int",
            "#          ge: 0",
            "#          stats: {mean: {between: [1000, 100000]}}",
            "#          conditions: [{le: 300000, severity: WARNING, name: implausibly high}]",
            "#    series:",
            "#      aadt_by_site: {value: aadt, group_by: [site_id], time_column: year}",
            "#    checks:",
            "#      - {check: missing_periods, series: aadt_by_site, expected: 2020..2023}",
            "#      - {check: change_rate, series: aadt_by_site, max: 0.15, tags: [nightly]}",
        ]
    lines += [
        "",
        "# Databases attached by `database` and `query` sources (use ${ENV_VAR} for secrets).",
        "connections: {}",
        "#  warehouse: {type: postgres, uri: 'host=db user=qa password=${PGPASSWORD} dbname=dw'}",
        "",
        "# Checks relating several datasets; each dataset is a table under its name in SQL.",
        "checks: []",
        "#  - check: sql",
        "#    name: totals match",
        "#    sql: SELECT * FROM summary s WHERE s.total <> (SELECT sum(x) FROM detail)",
        "#  - check: compare                 # traffic@* : every copy of a dataset with across",
        "#    name: districts agree",
        "#    datasets: traffic@*",
        "#    strategy: consensus             # reference | sequential | all_pairs | consensus",
        "#    keys: [site_id, year]",
        "#    decision: material              # no significance test; needs no stats extra",
        "",
        "# Available checks (name, rule code, where it goes; schema checks need no item):",
    ]
    for rule in registry:
        definition = definition_for(rule)
        where = {"dataset": "dataset", "top": "top level"}[definition.placement]
        if not definition.configurable:
            where = "schema"
        elif isinstance(definition, PluginDefinition):
            where = "dataset or top level"
        lines.append(f"#   {rule.check_name:<18} {rule.rule_id:<9} {where:<9} {rule.name}")
    lines += [
        "",
        "run:",
        _dump(RunSettings().model_dump(mode="json"), 2).rstrip(),
        "",
        "engine:",
        _dump(
            EngineSettings().model_dump(mode="json", by_alias=True, exclude={"execution_mode"}), 2
        ).rstrip(),
        "  # execution_mode: in_process (isolated when a process_* limit is set)",
        "",
        "plugins:",
        _dump(PluginSettings().model_dump(mode="json", by_alias=True), 2).rstrip(),
        "",
        "report:",
        _dump(ReportSettings().model_dump(mode="json", by_alias=True), 2).rstrip(),
        "",
        "# Settings for plugins, keyed by plugin name.",
        "extensions: {}",
        "",
    ]
    return "\n".join(lines)


def _render_starter(
    datasets: Mapping[str, Mapping[str, Any]] | None,
    *,
    project: str,
    schema_reference: str | None,
) -> str:
    """The minimal starter: the project, its datasets and pointers to the next steps."""
    stamp = datetime.now(UTC).strftime("%Y-%m-%d")
    lines = []
    if schema_reference:
        lines.append(f"# yaml-language-server: $schema={schema_reference}")
    lines += [
        f"# QAVF {__version__} starter configuration, generated by `qavf init` on {stamp}.",
        "# Schema contracts (columns, keys, foreign keys) always run; other checks run where",
        "# a `checks` list configures them. Inferred column limits reflect the profiled data;",
        "# review them before relying on them.",
        "",
        _dump({"project": project}).rstrip(),
        "",
    ]
    if datasets:
        lines.append("datasets:")
        for name, entry in datasets.items():
            lines.append(_dump({name: StarterEntries.entry(entry)}, 2).rstrip())
    else:
        lines += [
            "datasets: {}",
            "#  traffic:",
            "#    path: data/traffic.csv",
            "#    schema:",
            "#      primary_key: [site_id, year]",
            "#      columns:",
            "#        aadt: {dtype: int, ge: 0}",
        ]
    lines += [
        "",
        "# Next steps:",
        "#   qavf explain -c <this file>   validate it and show the plan, reading no data",
        "#   qavf list-checks              every check, its settings and where it goes",
        "#   qavf init --full              a reference of every setting and its default",
        "# A comparison of datasets goes in a top-level checks list, for example:",
        "#checks:",
        "#  - {check: compare, name: versions agree, datasets: [old, new], keys: [id],",
        "#     decision: material}",
        f"# Documentation: {DOCS_URL}",
        "",
    ]
    return "\n".join(lines)


# ---------------------------------------------------------------- JSON Schema
def config_json_schema(registry: RuleRegistry, sources: SourceRegistry) -> dict[str, Any]:
    """JSON Schema for configuration files, specialised to the installed rules and sources.

    Each check's settings and each source type's options are typed, so editors
    can autocomplete and validate them.
    """
    dataset_checks, top_checks = check_item_models(registry)
    source_models = tuple(source.Params for source in sources)
    source_type: Any = source_models[0] if source_models else dict[str, Any]
    for model in source_models[1:]:
        source_type = source_type | model
    dataset_model = create_model(
        "Dataset",
        __base__=DatasetSpec,
        source=(source_type | None, Field(default=None)),
        checks=(list[checks_union(dataset_checks)], Field(default_factory=list)),  # type: ignore[misc,arg-type]
    )
    root = create_model(
        "QAVFConfig",
        __base__=QAVFSettings,
        datasets=(dict[str, dataset_model], Field(default_factory=dict)),  # type: ignore[valid-type]
        checks=(list[checks_union(top_checks)], Field(default_factory=list)),  # type: ignore[misc,arg-type]
    )
    schema = root.model_json_schema(by_alias=True)
    schema["properties"].pop("source_path", None)
    schema["properties"]["$schema"] = {"type": "string"}
    schema["title"] = "QAVF configuration"
    schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
    from qavf.checks.schema import accept_reuse_values
    from qavf.schema_hints import apply_ui_hints

    return apply_ui_hints(accept_reuse_values(schema))


def write_json_schema(schema: Mapping[str, Any]) -> str:
    """Serialise a schema with stable formatting."""
    return json.dumps(schema, indent=2, sort_keys=False) + "\n"


