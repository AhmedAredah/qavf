"""Configuration scaffolding: profiling data into QA limits, ``qavf init`` and JSON Schema.

``qavf init`` writes a complete configuration listing every discovered rule with
its default parameters, and, given data files, a schema per dataset whose QA
limits (types, nullability, observed bounds, allowed values) are inferred from
the data. Inferred limits are a starting point to review, not a verdict: they
encode whatever the sample contained, including its errors.
"""

from __future__ import annotations

import json
from collections.abc import Mapping
from dataclasses import dataclass
from datetime import UTC, datetime
from typing import Any

import yaml
from pydantic import ConfigDict, Field, ValidationError, create_model

from qavf._version import __version__
from qavf.docgen import _type_name
from qavf.engine.registry import RuleRegistry
from qavf.engine.severity import Severity
from qavf.profiling import profile_frame as profile_frame
from qavf.profiling.values import validate_margin as validate_margin
from qavf.redaction import exception_details
from qavf.settings import (
    DatasetSpec,
    EngineSettings,
    PluginSettings,
    QAVFSettings,
    ReportSettings,
)
from qavf.sources.base import SourceRegistry

SCHEMA_FILENAME = "qavf.schema.json"


# ------------------------------------------------------------------ rendering
def _dump(value: Any, indent: int = 0) -> str:
    text = yaml.safe_dump(value, sort_keys=False, default_flow_style=False, allow_unicode=True)
    pad = " " * indent
    return "".join(pad + line if line.strip() else line for line in text.splitlines(True))


@dataclass(frozen=True)
class _ParameterDefaults:
    required: tuple[str, ...]
    defaults: dict[str, Any] | None
    diagnostic: str | None = None


def _parameter_defaults(rule: Any) -> _ParameterDefaults:
    """Keep declared fields, external aliases and defaultability independent."""
    required = tuple(
        name for name, field in rule.Params.model_fields.items() if field.is_required()
    )
    try:
        params = rule.Params()
    except ValidationError as exc:
        return _ParameterDefaults(required, None, exception_details(exc))
    return _ParameterDefaults(required, params.model_dump(mode="json", by_alias=True))


def render_config(
    registry: RuleRegistry,
    datasets: Mapping[str, Mapping[str, Any]] | None = None,
    *,
    project: str = "QA run",
    schema_reference: str | None = SCHEMA_FILENAME,
) -> str:
    """Render a complete, commented YAML configuration.

    Args:
        registry: Rules to list (every rule appears with its defaults).
        datasets: Dataset entries (``path``/``source`` plus ``schema``) to include.
        project: Project name.
        schema_reference: JSON Schema path for the editor header comment, or ``None``.
    """
    stamp = datetime.now(UTC).strftime("%Y-%m-%d")
    lines = []
    if schema_reference:
        lines.append(f"# yaml-language-server: $schema={schema_reference}")
    lines += [
        f"# QAVF {__version__} configuration, generated by `qavf init` on {stamp}.",
        "# Every discovered rule is listed with its default parameters: edit, disable",
        "# (enabled: false) or delete entries. Rules left out run with their defaults.",
        "# Inferred column limits reflect the profiled data; review them before relying on them.",
        "",
        _dump({"project": project}).rstrip(),
        "",
        "# Datasets: where data comes from and the QA limits for each column.",
        "# Sources: path (file/glob), or source: {type: file|query|database|python, ...}.",
    ]
    if datasets:
        lines.append("datasets:")
        for name, entry in datasets.items():
            lines.append(_dump({name: dict(entry)}, 2).rstrip())
    else:
        lines += [
            "datasets: {}",
            "#  traffic:",
            "#    path: data/traffic.csv",
            "#    schema:",
            "#      primary_key: [site_id, year]",
            "#      columns:",
            "#        aadt: {dtype: int, ge: 0, checks: [{le: 300000, severity: WARNING}]}",
        ]
    lines += [
        "",
        "# Databases attached by `database` and `query` sources (use ${ENV_VAR} for secrets).",
        "connections: {}",
        "#  warehouse: {type: postgres, uri: 'host=db user=qa password=${PGPASSWORD} dbname=dw'}",
        "",
        "# SQL queries returning offending rows; each dataset is a table under its name.",
        "assertions: []",
        "#  - name: totals match",
        "#    sql: SELECT * FROM summary s WHERE s.total <> (SELECT sum(x) FROM detail)",
        "",
        "rules:",
    ]
    for rule in registry:
        parameters = _parameter_defaults(rule)
        defaultable = parameters.defaults is not None
        for line in f"{rule.rule_id} · {rule.name} [{rule.category}]".splitlines():
            lines.append(f"  # {line}")
        for line in rule.description.splitlines():
            lines.append(f"  #   {line}")
        if not defaultable:
            # Never pretend required values exist: write the rule disabled, with what
            # it needs, so the configuration loads and plans as generated.
            lines.append("  #   Required parameters (set them under params, then enable the rule):")
            for name in parameters.required:
                field = rule.Params.model_fields[name]
                alias = field.validation_alias or field.alias or name
                description = " ".join((field.description or "").split())
                lines.append(
                    f"  #     {alias}: {_type_name(field.annotation)}"
                    + (f"  - {description}" if description else "")
                )
            if parameters.diagnostic:
                lines.append("  #   " + " ".join(parameters.diagnostic.split()))
        rule_entry: dict[str, Any] = {
            "enabled": defaultable,
            "severity": rule.default_severity.value,
        }
        if defaultable:
            rule_entry["params"] = parameters.defaults
        lines.append(_dump({rule.rule_id: rule_entry}, 2).rstrip())
    lines += [
        "",
        "engine:",
        _dump(EngineSettings().model_dump(mode="json", by_alias=True), 2).rstrip(),
        "",
        "plugins:",
        _dump(PluginSettings().model_dump(mode="json", by_alias=True), 2).rstrip(),
        "",
        "report:",
        _dump(ReportSettings().model_dump(mode="json", by_alias=True), 2).rstrip(),
        "",
        "# Settings for plugins, keyed by plugin name.",
        "extensions: {}",
        "",
    ]
    return "\n".join(lines)


# ---------------------------------------------------------------- JSON Schema
def config_json_schema(registry: RuleRegistry, sources: SourceRegistry) -> dict[str, Any]:
    """JSON Schema for configuration files, specialised to the installed rules and sources.

    Each rule's ``params`` and each source type's options are typed, so editors
    can autocomplete and validate them.
    """
    strict = ConfigDict(extra="forbid", populate_by_name=True)
    rule_fields: dict[str, Any] = {}
    for index, rule in enumerate(registry):
        model_name = f"Rule_{index}_" + "".join(ch if ch.isalnum() else "_" for ch in rule.rule_id)
        # Mirror runtime mapping/defaultability rules. Arbitrary model validators
        # remain runtime checks; JSON Schema cannot infer their predicates.
        config = strict
        if _parameter_defaults(rule).defaults is None:
            config = ConfigDict(
                extra="forbid",
                populate_by_name=True,
                json_schema_extra={
                    "if": {"properties": {"enabled": {"const": False}}, "required": ["enabled"]},
                    "else": {"required": ["params"]},
                },
            )
        settings_model = create_model(
            model_name,
            __config__=config,
            enabled=(bool, True),
            severity=(Severity | None, None),
            params=(rule.Params, Field(default_factory=dict)),
        )
        rule_fields[model_name] = (
            settings_model,
            Field(
                default_factory=dict,
                alias=rule.rule_id,
                description=f"{rule.name}. {rule.description}",
            ),
        )
    rules_model = create_model("Rules", __config__=strict, **rule_fields)

    source_models = tuple(source.Params for source in sources)
    source_type: Any = source_models[0] if source_models else dict[str, Any]
    for model in source_models[1:]:
        source_type = source_type | model
    dataset_model = create_model(
        "Dataset", __base__=DatasetSpec, source=(source_type | None, Field(default=None))
    )
    root = create_model(
        "QAVFConfig",
        __base__=QAVFSettings,
        datasets=(dict[str, dataset_model], Field(default_factory=dict)),  # type: ignore[valid-type]
        rules=(rules_model, Field(default_factory=rules_model)),
    )
    schema = root.model_json_schema(by_alias=True)
    schema["properties"].pop("source_path", None)
    schema["properties"]["$schema"] = {"type": "string"}
    schema["title"] = "QAVF configuration"
    schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
    return schema


def write_json_schema(schema: Mapping[str, Any]) -> str:
    """Serialise a schema with stable formatting."""
    return json.dumps(schema, indent=2, sort_keys=False) + "\n"


